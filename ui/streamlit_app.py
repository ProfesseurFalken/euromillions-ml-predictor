        import base64
        
        ticket_data = f"EuroMillions: {ticket['balls'][0]}-{ticket['balls'][1]}-{ticket['balls'][2]}-{ticket['balls'][3]}-{ticket['balls'][4]} + {ticket['stars'][0]}-{ticket['stars'][1]}"
        
